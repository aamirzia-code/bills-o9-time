  static bool get rtl => lang == 'ur' || lang == 'ar';

  static const languages = {
    'en': 'English',
    'ur': 'اردو',
    'ar': 'العربية',
  };
}

String tr(String en) {
  if (L.lang == 'en') return en;
  final map = L.lang == 'ur' ? _ur : (L.lang == 'ar' ? _ar : null);
  return map?[en] ?? en;
}

